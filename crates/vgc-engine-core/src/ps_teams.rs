//! Showdown team sets as the BattleStream handles them: `Teams.unpack` /
//! `Teams.pack` (sim/teams.ts:120-347), the in-place edits PS's `Pokemon`
//! constructor makes to each set (sim/pokemon.ts:318-410; they show in the
//! `end` record's `p1team` / `p2team`), and the conversion to the engine's
//! [`TeamMember`].
//!
//! Sets are kept as [`Json`] objects so their key order (which
//! `JSON.stringify` prints) is PS's: `unpack`'s order for a packed team,
//! the player's own order for a JSON team, with the constructor's
//! additions appended.

use crate::pokemon::StatSpread;
use crate::ps_json::Json;
use crate::team::TeamMember;
use std::collections::HashMap;
use std::sync::OnceLock;

/// PS `toID`.
pub fn to_id(s: &str) -> String {
    s.chars().filter(|c| c.is_ascii_alphanumeric()).map(|c| c.to_ascii_lowercase()).collect()
}

struct Names {
    /// id -> (name, baseSpecies, abilities by slot).
    species: HashMap<String, (String, String, Vec<(String, String)>)>,
    items: HashMap<String, String>,
    abilities: HashMap<String, String>,
    /// id -> (name, type).
    moves: HashMap<String, (String, String)>,
    natures: HashMap<String, String>,
}

/// PS's dex names (`ps_names.json`, generated by tools/protocol/ps-names.js).
fn names() -> &'static Names {
    static N: OnceLock<Names> = OnceLock::new();
    N.get_or_init(|| {
        let v: serde_json::Value = serde_json::from_str(include_str!("ps_names.json")).expect("ps_names.json");
        let flat = |k: &str| -> HashMap<String, String> {
            v[k].as_object().map(|o| o.iter().map(|(id, n)| (id.clone(), n.as_str().unwrap_or("").to_string())).collect()).unwrap_or_default()
        };
        let species = v["species"]
            .as_object()
            .map(|o| {
                o.iter()
                    .map(|(id, e)| {
                        let ab = e[2].as_object().map(|a| a.iter().map(|(k, n)| (k.clone(), n.as_str().unwrap_or("").to_string())).collect()).unwrap_or_default();
                        (id.clone(), (e[0].as_str().unwrap_or("").to_string(), e[1].as_str().unwrap_or("").to_string(), ab))
                    })
                    .collect()
            })
            .unwrap_or_default();
        let moves = v["moves"]
            .as_object()
            .map(|o| o.iter().map(|(id, e)| (id.clone(), (e[0].as_str().unwrap_or("").to_string(), e[1].as_str().unwrap_or("").to_string()))).collect())
            .unwrap_or_default();
        Names { species, items: flat("items"), abilities: flat("abilities"), moves, natures: flat("natures") }
    })
}

#[derive(Clone, Copy)]
enum Table {
    Species,
    Items,
    Abilities,
    Moves,
    Natures,
}

fn dex_name(t: Table, name: &str) -> Option<String> {
    let id = to_id(name);
    let n = names();
    match t {
        Table::Species => n.species.get(&id).map(|e| e.0.clone()),
        Table::Items => n.items.get(&id).cloned(),
        Table::Abilities => n.abilities.get(&id).cloned(),
        Table::Moves => n.moves.get(&id).map(|e| e.0.clone()),
        Table::Natures => n.natures.get(&id).cloned(),
    }
}

/// `Teams.unpackName` (sim/teams.ts:355-365).
fn unpack_name(name: &str, t: Table) -> String {
    if name.is_empty() {
        return String::new();
    }
    if let Some(n) = dex_name(t, name) {
        return n;
    }
    // name.replace(/([0-9]+)/g, ' $1 ').replace(/([A-Z])/g, ' $1').replace(/[ ][ ]/g, ' ').trim()
    let mut a = String::new();
    let cs: Vec<char> = name.chars().collect();
    let mut i = 0;
    while i < cs.len() {
        if cs[i].is_ascii_digit() {
            a.push(' ');
            while i < cs.len() && cs[i].is_ascii_digit() {
                a.push(cs[i]);
                i += 1;
            }
            a.push(' ');
        } else {
            a.push(cs[i]);
            i += 1;
        }
    }
    let mut b = String::new();
    for c in a.chars() {
        if c.is_ascii_uppercase() {
            b.push(' ');
        }
        b.push(c);
    }
    // /[ ][ ]/g replaces non-overlapping pairs once.
    let mut c = String::new();
    let bc: Vec<char> = b.chars().collect();
    let mut i = 0;
    while i < bc.len() {
        if bc[i] == ' ' && bc.get(i + 1) == Some(&' ') {
            c.push(' ');
            i += 2;
        } else {
            c.push(bc[i]);
            i += 1;
        }
    }
    c.trim_matches(|ch: char| ch.is_whitespace()).to_string()
}

/// `Teams.packName` (sim/teams.ts:349-353).
pub fn pack_name(name: &str) -> String {
    name.chars().filter(|c| c.is_ascii_alphanumeric()).collect()
}

/// JS `Number(s)` for the strings a packed team holds (NaN for junk).
fn js_number(s: &str) -> f64 {
    let t = s.trim();
    if t.is_empty() {
        return 0.0;
    }
    t.parse::<f64>().unwrap_or(f64::NAN)
}

/// `Number(s) || 0`.
fn num_or0(s: &str) -> Json {
    let n = js_number(s);
    Json::Num(if n.is_nan() || n == 0.0 { 0.0 } else { n })
}

/// JS `parseInt(s)`.
fn js_parse_int(s: &str) -> Option<f64> {
    let t = s.trim_start();
    let (neg, rest) = match t.as_bytes().first() {
        Some(b'-') => (true, &t[1..]),
        Some(b'+') => (false, &t[1..]),
        _ => (false, t),
    };
    let d: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
    if d.is_empty() {
        return None;
    }
    let v: f64 = d.parse().unwrap_or(f64::NAN);
    Some(if neg { -v } else { v })
}

/// `Teams.unpack` (sim/teams.ts:215-347): `None` for a malformed team.
pub fn unpack(buf: &str) -> Option<Vec<Json>> {
    if buf.is_empty() {
        return None;
    }
    if buf.starts_with('[') && buf.ends_with(']') {
        let team = Json::parse(buf).ok()?;
        let Json::Arr(sets) = team else { return None };
        return unpack(&pack(&sets));
    }
    let mut team = Vec::new();
    let mut i = 0usize;
    let find = |from: usize, c: char| buf[from.min(buf.len())..].find(c).map(|k| from + k);
    for _ in 0..24 {
        let mut set = Json::obj();
        // name
        let j = find(i, '|')?;
        let name = buf[i..j].to_string();
        set.set("name", Json::Str(name.clone()));
        i = j + 1;
        // species
        let j = find(i, '|')?;
        let sp = unpack_name(&buf[i..j], Table::Species);
        set.set("species", Json::Str(if sp.is_empty() { name.clone() } else { sp }));
        i = j + 1;
        // item
        let j = find(i, '|')?;
        set.set("item", Json::Str(unpack_name(&buf[i..j], Table::Items)));
        i = j + 1;
        // ability
        let j = find(i, '|')?;
        let ability = &buf[i..j];
        let ab = if ["", "0", "1", "H", "S"].contains(&ability) {
            let slot = if ability.is_empty() { "0" } else { ability };
            let species_id = to_id(set.str_of("species"));
            let found = names().species.get(&species_id).and_then(|e| e.2.iter().find(|(k, _)| k == slot).map(|(_, n)| n.clone()));
            match found {
                Some(n) if !n.is_empty() => n,
                _ if ability.is_empty() => String::new(),
                _ => "!!!ERROR!!!".to_string(),
            }
        } else {
            unpack_name(ability, Table::Abilities)
        };
        set.set("ability", Json::Str(ab));
        i = j + 1;
        // moves
        let j = find(i, '|')?;
        let moves: Vec<Json> = buf[i..j].split(',').take(24).map(|m| Json::Str(unpack_name(m, Table::Moves))).collect();
        set.set("moves", Json::Arr(moves));
        i = j + 1;
        // nature
        let j = find(i, '|')?;
        set.set("nature", Json::Str(unpack_name(&buf[i..j], Table::Natures)));
        i = j + 1;
        // evs
        let j = find(i, '|')?;
        if j != i {
            let e: Vec<&str> = buf[i..j].split(',').take(6).collect();
            let g = |k: usize| num_or0(e.get(k).copied().unwrap_or(""));
            let mut evs = Json::obj();
            for (k, stat) in ["hp", "atk", "def", "spa", "spd", "spe"].into_iter().enumerate() {
                evs.set(stat, g(k));
            }
            set.set("evs", evs);
        }
        i = j + 1;
        // gender
        let j = find(i, '|')?;
        if i != j {
            set.set("gender", Json::Str(buf[i..j].to_string()));
        }
        i = j + 1;
        // ivs
        let j = find(i, '|')?;
        if j != i {
            let e: Vec<&str> = buf[i..j].split(',').take(6).collect();
            let mut ivs = Json::obj();
            for (k, stat) in ["hp", "atk", "def", "spa", "spd", "spe"].into_iter().enumerate() {
                let s = e.get(k).copied();
                // `ivs[k] === ''` is 31; a missing entry is `Number(undefined) || 0`.
                ivs.set(stat, if s == Some("") { Json::Num(31.0) } else { num_or0(s.unwrap_or("x")) });
            }
            set.set("ivs", ivs);
        }
        i = j + 1;
        // shiny
        let j = find(i, '|')?;
        if i != j {
            set.set("shiny", Json::Bool(true));
        }
        i = j + 1;
        // level
        let j = find(i, '|')?;
        if i != j {
            set.set("level", js_parse_int(&buf[i..j]).map(Json::Num).unwrap_or(Json::Num(f64::NAN)));
        }
        i = j + 1;
        // happiness, then the misc fields
        let j = find(i, ']');
        let misc: Option<Vec<&str>> = match j {
            None if i < buf.len() => Some(buf[i..].split(',').take(6).collect()),
            Some(j) if i != j => Some(buf[i..j].split(',').take(6).collect()),
            _ => None,
        };
        if let Some(m) = misc {
            let at = |k: usize| m.get(k).copied().unwrap_or("");
            set.set("happiness", if at(0).is_empty() { Json::Num(255.0) } else { Json::Num(js_number(at(0))) });
            set.set("hpType", Json::Str(at(1).to_string()));
            set.set("pokeball", Json::Str(unpack_name(at(2), Table::Items)));
            set.set("gigantamax", Json::Bool(!at(3).is_empty()));
            set.set("dynamaxLevel", if at(4).is_empty() { Json::Num(10.0) } else { Json::Num(js_number(at(4))) });
            // `set.teraType = misc[5]`: undefined (dropped by JSON.stringify) when absent.
            if let Some(t) = m.get(5) {
                set.set("teraType", Json::Str(t.to_string()));
            }
        }
        team.push(set);
        match j {
            None => break,
            Some(j) => i = j + 1,
        }
    }
    Some(team)
}

/// `String(x)` for a set's scalar fields.
fn js_string(v: Option<&Json>) -> String {
    match v {
        None | Some(Json::Null) => String::new(),
        Some(Json::Str(s)) => s.clone(),
        Some(Json::Num(n)) => crate::ps_json::js_number(*n),
        Some(Json::Bool(b)) => b.to_string(),
        Some(_) => String::new(),
    }
}

/// `x || ''` then string interpolation.
fn or_empty(v: Option<&Json>) -> String {
    match v {
        Some(j) if j.truthy() => js_string(Some(j)),
        _ => String::new(),
    }
}

/// `Teams.pack` (sim/teams.ts:120-213).
pub fn pack(team: &[Json]) -> String {
    let mut buf = String::new();
    for set in team {
        if !buf.is_empty() {
            buf.push(']');
        }
        let name = or_empty(set.get("name"));
        let species = or_empty(set.get("species"));
        // name
        buf.push_str(if name.is_empty() { &species } else { &name });
        // species
        let id = pack_name(if species.is_empty() { &name } else { &species });
        let named = pack_name(if name.is_empty() { &species } else { &name });
        buf.push('|');
        if named != id {
            buf.push_str(&id);
        }
        buf.push('|');
        buf.push_str(&pack_name(&or_empty(set.get("item"))));
        buf.push('|');
        buf.push_str(&pack_name(&or_empty(set.get("ability"))));
        buf.push('|');
        if let Some(Json::Arr(m)) = set.get("moves") {
            let ms: Vec<String> = m.iter().map(|x| pack_name(&or_empty(Some(x)))).collect();
            buf.push_str(&ms.join(","));
        }
        buf.push('|');
        buf.push_str(&or_empty(set.get("nature")));
        // evs
        let mut evs = "|".to_string();
        if let Some(e) = set.get("evs").filter(|e| e.truthy()) {
            let g = |k: &str| or_empty(e.get(k));
            evs = format!("|{},{},{},{},{},{}", g("hp"), g("atk"), g("def"), g("spa"), g("spd"), g("spe"));
        }
        buf.push_str(if evs == "|,,,,," { "|" } else { &evs });
        // gender
        buf.push('|');
        buf.push_str(&or_empty(set.get("gender")));
        // ivs
        let mut ivs = "|".to_string();
        if let Some(e) = set.get("ivs").filter(|e| e.truthy()) {
            let g = |k: &str| match e.get(k) {
                None => String::new(),
                Some(Json::Num(n)) if *n == 31.0 => String::new(),
                Some(v) => js_string(Some(v)),
            };
            ivs = format!("|{},{},{},{},{},{}", g("hp"), g("atk"), g("def"), g("spa"), g("spd"), g("spe"));
        }
        buf.push_str(if ivs == "|,,,,," { "|" } else { &ivs });
        // shiny
        buf.push_str(if set.get("shiny").is_some_and(Json::truthy) { "|S" } else { "|" });
        // level
        buf.push('|');
        if let Some(l) = set.get("level").filter(|l| l.truthy() && l.as_f64() != Some(100.0)) {
            buf.push_str(&js_string(Some(l)));
        }
        // happiness
        buf.push('|');
        if let Some(h) = set.get("happiness").filter(|h| h.as_f64() != Some(255.0)) {
            buf.push_str(&js_string(Some(h)));
        }
        let dl = set.get("dynamaxLevel");
        let dl_set = dl.is_some_and(|d| d.as_f64() != Some(10.0));
        if set.get("pokeball").is_some_and(Json::truthy)
            || set.get("hpType").is_some_and(Json::truthy)
            || set.get("gigantamax").is_some_and(Json::truthy)
            || dl_set
            || set.get("teraType").is_some_and(Json::truthy)
        {
            buf.push(',');
            buf.push_str(&or_empty(set.get("hpType")));
            buf.push(',');
            buf.push_str(&pack_name(&or_empty(set.get("pokeball"))));
            buf.push(',');
            if set.get("gigantamax").is_some_and(Json::truthy) {
                buf.push('G');
            }
            buf.push(',');
            if dl_set {
                buf.push_str(&js_string(dl));
            }
            buf.push(',');
            buf.push_str(&or_empty(set.get("teraType")));
        }
    }
    buf
}

/// `clampIntRange` (lib/utils.ts:320-326).
fn clamp_int(v: Option<&Json>, min: f64, max: f64) -> f64 {
    let n = match v {
        Some(Json::Num(n)) => n.floor(),
        _ => 0.0,
    };
    let n = if n.is_nan() { min } else { n };
    n.clamp(min, max)
}

/// The edits PS's `Pokemon` constructor makes to its set
/// (sim/pokemon.ts:328-402): the default name, the level, a Hidden Power
/// type, and the EV / IV tables filled in and clamped. `Err` names a set
/// PS would reject (unknown species, no moves).
pub fn normalize_set(set: &mut Json) -> Result<(), String> {
    let species_key = {
        let s = set.str_of("species");
        if s.is_empty() { set.str_of("name").to_string() } else { s.to_string() }
    };
    let Some((_, base, _)) = names().species.get(&to_id(&species_key)).cloned() else {
        return Err(format!("Unidentified species: {species_key}"));
    };
    let name = set.get("name").cloned();
    let renamed = match (&name, set.get("species")) {
        (None, _) => true,
        (Some(n), _) if !n.truthy() => true,
        (Some(n), Some(s)) => n == s,
        _ => false,
    };
    if renamed {
        set.set("name", Json::Str(base));
    }
    let level = match set.get("adjustLevel").filter(|l| l.truthy()) {
        Some(l) => Some(l.clone()),
        None => set.get("level").filter(|l| l.truthy()).cloned(),
    };
    let level = clamp_int(Some(&level.unwrap_or(Json::Num(100.0))), 1.0, 9999.0);
    set.set("level", Json::Num(level));
    let moves: Vec<String> = match set.get("moves") {
        Some(Json::Arr(m)) if !m.is_empty() => m.iter().map(|x| js_string(Some(x))).collect(),
        _ => return Err(format!("Set {} has no moves", set.str_of("name"))),
    };
    for m in &moves {
        let id = to_id(m);
        if id.starts_with("hiddenpower") {
            let ty = names().moves.get(&id).map(|e| e.1.clone()).unwrap_or_default();
            if ty != "Normal" && !ty.is_empty() && !set.get("hpType").is_some_and(Json::truthy) {
                set.set("hpType", Json::Str(ty));
            }
        }
    }
    if !set.get("evs").is_some_and(Json::truthy) {
        let mut e = Json::obj();
        for s in ["hp", "atk", "def", "spa", "spd", "spe"] {
            e.set(s, Json::Num(0.0));
        }
        set.set("evs", e);
    }
    if !set.get("ivs").is_some_and(Json::truthy) {
        let mut e = Json::obj();
        for s in ["hp", "atk", "def", "spa", "spd", "spe"] {
            e.set(s, Json::Num(31.0));
        }
        set.set("ivs", e);
    }
    // `const stats = { hp, atk, def, spe, spa, spd }`: missing keys are added in this order.
    for s in ["hp", "atk", "def", "spe", "spa", "spd"] {
        if let Some(e) = set.get_mut("evs") {
            if !e.get(s).is_some_and(Json::truthy) {
                e.set(s, Json::Num(0.0));
            }
        }
        if let Some(e) = set.get_mut("ivs") {
            let v = e.get(s);
            let zero = matches!(v, Some(Json::Num(n)) if *n == 0.0);
            if !v.is_some_and(Json::truthy) && !zero {
                e.set(s, Json::Num(31.0));
            }
        }
    }
    for (k, max) in [("evs", 255.0), ("ivs", 31.0)] {
        if let Some(Json::Obj(e)) = set.get_mut(k) {
            for (_, v) in e.iter_mut() {
                *v = Json::Num(clamp_int(Some(v), 0.0, max));
            }
        }
    }
    Ok(())
}

fn stat_spread(v: Option<&Json>, default: u8) -> StatSpread {
    let g = |k: &str| v.and_then(|e| e.get(k)).and_then(Json::as_f64).map(|n| n.clamp(0.0, 255.0) as u8).unwrap_or(default);
    StatSpread { hp: g("hp"), atk: g("atk"), def: g("def"), spa: g("spa"), spd: g("spd"), spe: g("spe") }
}

/// The engine's team member for a normalized set (its moves PS can't
/// identify are dropped, as PS does).
pub fn to_member(set: &Json) -> TeamMember {
    let species = {
        let s = set.str_of("species");
        if s.is_empty() { set.str_of("name").to_string() } else { s.to_string() }
    };
    let opt = |k: &str| Some(set.str_of(k).to_string()).filter(|s| !s.is_empty());
    let moves = match set.get("moves") {
        Some(Json::Arr(m)) => m.iter().map(|x| js_string(Some(x))).filter(|m| names().moves.contains_key(&to_id(m))).collect(),
        _ => Vec::new(),
    };
    let nature = Some(set.str_of("nature")).filter(|n| names().natures.contains_key(&to_id(n))).unwrap_or("serious").to_string();
    TeamMember {
        species,
        level: set.get("level").and_then(Json::as_f64).map(|l| l.clamp(1.0, 255.0) as u8).unwrap_or(100),
        ability: opt("ability"),
        item: opt("item"),
        nature,
        moves,
        ivs: stat_spread(set.get("ivs"), 31),
        evs: stat_spread(set.get("evs"), 0),
        teratype: opt("teraType"),
        gender: Some(set.str_of("gender").to_string()).filter(|g| matches!(g.as_str(), "M" | "F" | "N")),
    }
}

/// Champions sets carry Stat Points in `evs`. PS's Champions `statModify`
/// (data/mods/champions/scripts.ts:10-40) adds them to the base stat and
/// ignores IVs and level; at level 50 that equals the main-series formula
/// with `8 * sp - 4` EVs (0 for 0) and 31 IVs, which is what the engine
/// computes (and recomputes on Mega Evolution). Exact at level 50 only, as
/// in the conformance harness (vgc-engine-conformance `build_engine_team`).
pub fn champions_stat_points(m: &mut TeamMember) {
    let ev = |sp: u8| if sp == 0 { 0 } else { (8 * sp as u16 - 4).min(255) as u8 };
    m.ivs = StatSpread::MAX_IV;
    m.evs = StatSpread { hp: ev(m.evs.hp), atk: ev(m.evs.atk), def: ev(m.evs.def), spa: ev(m.evs.spa), spd: ev(m.evs.spd), spe: ev(m.evs.spe) };
}

/// The name PS gives the mon (sim/pokemon.ts:334, `set.name.substr(0, 20)`).
pub fn display_name(set: &Json) -> String {
    set.str_of("name").chars().take(20).collect()
}

